import mongoose from 'mongoose';
import { SPLIT_TYPES } from '../shared/split.js';

export const CATEGORIES = [
  'food',
  'groceries',
  'travel',
  'stay',
  'rent',
  'utilities',
  'entertainment',
  'shopping',
  'other',
];

const splitSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    amount: { type: Number, required: true, min: 0 }, // paise
    value: { type: Number, default: null }, // what the user typed: rupees / % / shares
  },
  { _id: false },
);

const expenseSchema = new mongoose.Schema(
  {
    group: { type: mongoose.Schema.Types.ObjectId, ref: 'Group', required: true },
    description: { type: String, required: true, trim: true, maxlength: 100 },
    notes: { type: String, trim: true, maxlength: 500, default: '' },
    amount: { type: Number, required: true, min: 1 }, // paise, integer
    paidBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    splitType: { type: String, enum: SPLIT_TYPES, required: true },
    splits: { type: [splitSchema], required: true },
    category: { type: String, enum: CATEGORIES, default: 'other' },
    date: { type: Date, required: true },
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    // Soft delete keeps the audit trail intact.
    deletedAt: { type: Date, default: null },
    deletedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    // Idempotency: the client generates one id per "Add expense" form, so a
    // double-click or a retried request can never create the expense twice.
    clientRequestId: { type: String },
    // Set when the expense was generated by a recurring rule.
    recurring: { type: mongoose.Schema.Types.ObjectId, ref: 'RecurringExpense' },
    occurrenceKey: { type: String },
  },
  { timestamps: true },
);

expenseSchema.index({ group: 1, deletedAt: 1, date: -1, createdAt: -1 });
expenseSchema.index(
  { group: 1, clientRequestId: 1 },
  { unique: true, partialFilterExpression: { clientRequestId: { $type: 'string' } } },
);
expenseSchema.index(
  { recurring: 1, occurrenceKey: 1 },
  { unique: true, partialFilterExpression: { occurrenceKey: { $type: 'string' } } },
);

export const Expense = mongoose.model('Expense', expenseSchema);
